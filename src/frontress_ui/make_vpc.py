#!/usr/bin/env python3
"""Write frontress_ui.vpc: the UI runtime plus RmlUi's core, as one static
library. Run it again after updating src/thirdparty/RmlUi.

    python3 src/frontress_ui/make_vpc.py
"""
import glob
import os

SRC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(SRC)

HEADER = r'''//-----------------------------------------------------------------------------
// frontress_ui: the menus' runtime (src/frontress_ui) and RmlUi, its HTML/CSS
// layout engine (src/thirdparty/RmlUi, MIT). A static library of its own, so
// RmlUi's file names (Element.cpp, Factory.cpp...) never meet the client's.
// Nothing here includes Source headers; the client links it and draws it
// (src/game/client/tf/frontress/fui_host.cpp).
//
// Generated by src/frontress_ui/make_vpc.py. RmlUi's debugger is left out
// of the game (the previewer has it).
//-----------------------------------------------------------------------------

$Macro SRCDIR		".."
$Macro OUTLIBDIR	"$LIBCOMMON"

$Conditional THIRDPARTYPROJECT "true"

$include "$SRCDIR\vpc_scripts\source_lib_base.vpc"

$Configuration
{
	$Compiler
	{
		$AdditionalIncludeDirectories	"$BASE;$SRCDIR\thirdparty\RmlUi\Include;$SRCDIR\frontress_ui"
		$PreprocessorDefinitions		"$BASE;RMLUI_STATIC_LIB;_CRT_SECURE_NO_WARNINGS"
		$TreatWarningsAsErrors			"No"
	}
}
'''


def files(paths):
    return "".join('\t\t$File\t"$SRCDIR\\%s"\n' % p.replace("/", "\\") for p in sorted(paths))


def main():
    fui = glob.glob("frontress_ui/*.cpp") + glob.glob("frontress_ui/*.h")
    rml = glob.glob("thirdparty/RmlUi/Source/Core/**/*.cpp", recursive=True) + glob.glob("thirdparty/RmlUi/Source/Core/**/*.h", recursive=True)
    names = [os.path.basename(p) for p in rml if p.endswith(".cpp")]
    dupes = sorted({n for n in names if names.count(n) > 1})
    if dupes:
        raise SystemExit("RmlUi has two files called %s; MSBuild would put both in one .obj" % ", ".join(dupes))
    body = '$Project "frontress_ui"\n{\n\t$Folder "frontress_ui"\n\t{\n%s\t}\n\t$Folder "RmlUi"\n\t{\n%s\t}\n}\n' % (files(fui), files(rml))
    with open("frontress_ui/frontress_ui.vpc", "w", newline="\n") as f:
        f.write(HEADER + "\n" + body)
    print("frontress_ui.vpc: %d files" % (len(fui) + len(rml)))


if __name__ == "__main__":
    main()
