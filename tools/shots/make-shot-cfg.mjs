// Turn the angles marked in a screenshot session into a replayable shot list.
//
//   node tools/shots/make-shot-cfg.mjs <map> [--log path/to/frontress_shots_marks.log] [--wait 90]
//
// frontress_shots.cfg logs `spec_pos` for every F6 press; this reads those
// lines (and `setpos ...;setang ...` from getpos, if you marked that way) and
// writes cfg/shots_<map>.cfg next to the log. In the game:
//
//   map <map>
//   exec frontress_shots
//   exec shots_<map>
//
// and the camera visits every mark, waits for the frame to settle and saves a
// JPEG. The log is cleared of the marks it used, so the next session starts
// a fresh list.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname( fileURLToPath( import.meta.url ) );
const map = process.argv[ 2 ];
const opt = ( name, fallback ) => {
	const i = process.argv.indexOf( `--${ name }` );
	return i > 0 ? process.argv[ i + 1 ] : fallback;
};

if ( !map || map.startsWith( '--' ) || !/^[A-Za-z0-9_]+$/.test( map ) ) {
	console.error( 'usage: node make-shot-cfg.mjs <map> [--log <frontress_shots_marks.log>] [--wait <frames>]' );
	process.exit( 2 );
}

const log = path.resolve( opt( 'log', path.join( HERE, '../../game/tc2/cfg/frontress_shots_marks.log' ) ) );
const settle = Math.max( 10, +opt( 'wait', 90 ) );
if ( !fs.existsSync( log ) ) {
	console.error( `no marks log at ${ log }\n(run exec frontress_shots in the game first, or pass --log)` );
	process.exit( 1 );
}

const num = '(-?\\d+(?:\\.\\d+)?)';
const SPEC = new RegExp( `spec_goto\\s+${ num }\\s+${ num }\\s+${ num }\\s+${ num }\\s+${ num }` );
const SETPOS = new RegExp( `setpos\\s+${ num }\\s+${ num }\\s+${ num }\\s*;\\s*setang\\s+${ num }\\s+${ num }` );

const marks = [];
for ( const line of fs.readFileSync( log, 'utf8' ).split( /\r?\n/ ) ) {
	const m = line.match( SPEC ) || line.match( SETPOS );
	if ( !m )
		continue;
	const v = m.slice( 1, 6 ).map( x => ( +x ).toFixed( 1 ) );
	const key = v.join( ' ' );
	if ( !marks.some( k => k === key ) )
		marks.push( key );
}

if ( !marks.length ) {
	console.error( `no marks in ${ log } -- press F6 in the game after exec frontress_shots` );
	process.exit( 1 );
}

const out = path.join( path.dirname( log ), `shots_${ map }.cfg` );
const lines = [
	`// ${ marks.length } angles on ${ map }, generated by tools/shots/make-shot-cfg.mjs.`,
	`// map ${ map }; exec frontress_shots; exec shots_${ map }`,
	'spec_mode 7',   // OBS_MODE_ROAMING here; spec_goto only works in it
	'cl_drawhud 0',
	'hidepanel specgui',
	'',
];
marks.forEach( ( m, i ) => {
	lines.push( `echo "shot ${ i + 1 }/${ marks.length }"` );
	lines.push( `spec_goto ${ m }` );
	lines.push( `wait ${ settle }` );
	lines.push( 'jpeg' );
	lines.push( 'wait 20' );
} );
lines.push( `echo "shots_${ map }: done, see tc2/screenshots"` );
fs.writeFileSync( out, lines.join( '\n' ) + '\n' );

// Keep the log but drop the marks that are now in a shot list.
fs.writeFileSync( log, fs.readFileSync( log, 'utf8' ).split( /\r?\n/ )
	.filter( l => !SPEC.test( l ) && !SETPOS.test( l ) ).join( '\n' ) );

console.log( `${ marks.length } angles -> ${ out }` );
